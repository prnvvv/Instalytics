/** A 5 x 7 dot-matrix font: just the glyphs the dashboard needs. '1' is lit, '.' is dark. */

export const GLYPH_ROWS = 7

const g = (...rows: string[]) => rows.map(r => r.replaceAll('.', '0').replaceAll('#', '1'))

export const GLYPHS: Record<string, string[]> = {
  '0': g('.###.', '#...#', '#..##', '#.#.#', '##..#', '#...#', '.###.'),
  '1': g('..#..', '.##..', '..#..', '..#..', '..#..', '..#..', '.###.'),
  '2': g('.###.', '#...#', '....#', '...#.', '..#..', '.#...', '#####'),
  '3': g('####.', '....#', '....#', '.###.', '....#', '....#', '####.'),
  '4': g('...#.', '..##.', '.#.#.', '#..#.', '#####', '...#.', '...#.'),
  '5': g('#####', '#....', '####.', '....#', '....#', '#...#', '.###.'),
  '6': g('..##.', '.#...', '#....', '####.', '#...#', '#...#', '.###.'),
  '7': g('#####', '....#', '...#.', '..#..', '.#...', '.#...', '.#...'),
  '8': g('.###.', '#...#', '#...#', '.###.', '#...#', '#...#', '.###.'),
  '9': g('.###.', '#...#', '#...#', '.####', '....#', '...#.', '.##..'),
  '.': g('.', '.', '.', '.', '.', '.', '#'),
  ',': g('..', '..', '..', '..', '..', '.#', '#.'),
  '%': g('##..#', '##.#.', '...#.', '..#..', '.#...', '.#.##', '#..##'),
  '-': g('.....', '.....', '.....', '#####', '.....', '.....', '.....'),
  '+': g('.....', '..#..', '..#..', '#####', '..#..', '..#..', '.....'),
  '/': g('....#', '...#.', '...#.', '..#..', '.#...', '.#...', '#....'),
  x: g('.....', '#...#', '.#.#.', '..#..', '.#.#.', '#...#', '.....'),
  N: g('#...#', '##..#', '#.#.#', '#..##', '#...#', '#...#', '#...#'),
  A: g('.###.', '#...#', '#...#', '#####', '#...#', '#...#', '#...#'),
  ' ': g('..', '..', '..', '..', '..', '..', '..')
}

/** The pixel columns of a string: one entry per column, each a 7-character string of 0/1. */
export const layoutText = (text: string): string[][] => {
  const columns: string[][] = []

  for (const char of text) {
    const glyph = GLYPHS[char] ?? GLYPHS[' ']

    // Spacer column between glyphs.
    if (columns.length > 0) columns.push(Array(GLYPH_ROWS).fill('0'))

    for (let x = 0; x < glyph[0].length; x++) columns.push(glyph.map(row => row[x]))
  }

  return columns
}
